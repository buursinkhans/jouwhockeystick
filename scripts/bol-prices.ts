// bol.com prices (writes code): looks up the current bol.com price of every
// stick with a confirmed bol.com product page through the Marketing Catalog
// API and writes them to src/catalog/offers/bolPrices.ts, for "Waar te koop"
// (docs/spec/prijsvergelijking.md, phase 1). Runs in the weekly PassaHockey
// sync, so prices reach the site through the same pull request (option A).
// Needs BOL_CLIENT_ID and BOL_CLIENT_SECRET; never prints them.
// Usage: npm run bol:prices -- [report.md]
import { writeFileSync } from 'node:fs';
import { getAllProducts } from '../src/catalog/index';
import type { BolPrices } from '../src/catalog/offers/index';
import { BOL_PRICES } from '../src/catalog/offers/bolPrices';
import { asBolProduct, bolProductIdFromUrl, findEan, get, getToken } from './bol-feed-check';

const OUT = 'src/catalog/offers/bolPrices.ts';

async function priceFor(url: string, token: string): Promise<number | null> {
  const bolId = bolProductIdFromUrl(url);
  if (!bolId) return null;
  const idBody = await get(`/products/${bolId}/to-ean`, token);
  const ean = idBody ? findEan(idBody) : null;
  if (!ean) return null;
  const body = await get(`/products/${ean}?country-code=NL&include-offer=true`, token);
  const price = body ? asBolProduct(body).offer?.price : undefined;
  return typeof price === 'number' && price > 0 ? price : null;
}

async function main() {
  const [reportPath = 'bol-prices.md'] = process.argv.slice(2);
  const token = await getToken();
  const products = getAllProducts(new Date(), { includeImported: true }).filter((p) => p.bolProductUrl);
  const prices: Record<string, number> = {};
  const missing: string[] = [];
  for (const product of products) {
    try {
      const price = await priceFor(product.bolProductUrl ?? '', token);
      if (price === null) missing.push(product.slug);
      else prices[product.slug] = price;
    } catch {
      missing.push(product.slug);
    }
  }
  // A failing API must never wipe last week's prices: keep the old file when far fewer prices came back.
  const before = Object.keys(BOL_PRICES.prices).length;
  const found = Object.keys(prices).length;
  if (found < Math.max(1, Math.floor(before / 2))) {
    throw new Error(`Maar ${found} bol.com-prijzen gevonden (vorige keer ${before}); bestand niet bijgewerkt.`);
  }
  const date = new Date().toISOString().slice(0, 10);
  const data: BolPrices = { date, prices };
  writeFileSync(
    OUT,
    [
      '// GENERATED by `npm run bol:prices` from the bol.com Marketing Catalog API.',
      '// Current bol.com price per stick with a confirmed bol.com page; see src/catalog/offers/index.ts.',
      "import type { BolPrices } from './index';",
      '',
      `export const BOL_PRICES: BolPrices = ${JSON.stringify(data)};`,
      '',
    ].join('\n'),
  );
  writeFileSync(
    reportPath,
    [
      '## bol.com-prijzen',
      '',
      `${found} van ${products.length} sticks met een bol.com-pagina hebben een actuele prijs bij bol.com.`,
      ...(missing.length ? ['', `Geen prijs gevonden (bol.com zonder bedrag): ${missing.map((s) => `\`${s}\``).join(', ')}`] : []),
      '',
    ].join('\n'),
  );
  console.log(`${found} bol.com-prijzen, ${missing.length} zonder prijs.`);
}

main().catch((error: unknown) => {
  // bol.com's error texts contain no credentials (see bol-feed-check.ts).
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
});
