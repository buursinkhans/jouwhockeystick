// Weekly import of the hockey shoes in the PassaHockey and Plutosport feeds
// into src/catalog/shoes/imported.ts (one model per shoe, colours merged,
// shops linked on EAN, every content property unknown). Runs in the weekly
// sync (passa-sync.yml) and writes a Dutch Markdown report for the sync PR.
// Writes nothing when a feed cannot be read, so last week's file stays.
// Usage: npm run shoes:import -- [report.md] [--passa-only] [--passa=file.xml] [--pluto=file.csv(.gz)]
// --passa-only is for a local run without the Awin secret (no Plutosport part).
import { writeFileSync } from 'node:fs';
import { buildShoeImport, type ShoeImportResult } from '../src/catalog/shoes/feedImport';
import { CURATED_SHOES } from '../src/catalog/shoes/products';
import { readPassa, readPlutosport, redact } from './shoe-feeds';

const OUTPUT = 'src/catalog/shoes/imported.ts';
/** Fewer models than this means a broken feed, not a smaller range. */
const MIN_PASSA_MODELS = 100;

function generated(date: string, feeds: readonly string[], result: ShoeImportResult): string {
  return [
    '// GENERATED by `npm run shoes:import` from the PassaHockey (TradeTracker) and Plutosport (Awin) product feeds.',
    '// Do not edit by hand: the weekly sync overwrites this file. To check a model by hand, copy it to',
    '// src/catalog/shoes/products/, fill its properties from the brand site and remove `feedImport`.',
    "import type { Shoe, ShoeListing } from './types';",
    '',
    `export const SHOE_IMPORT_DATE = '${date}';`,
    '',
    '/** The feeds this file was built from. */',
    `export const SHOE_IMPORT_FEEDS: readonly ('passahockey' | 'plutosport')[] = ${JSON.stringify(feeds)};`,
    '',
    'export const IMPORTED_SHOES: Shoe[] = [',
    ...result.shoes.map((shoe) => `  ${JSON.stringify(shoe)},`),
    '];',
    '',
    '/** Feed listings per slug, imported and hand-checked models alike (matched on EAN). */',
    'export const SHOE_LISTINGS: Record<string, ShoeListing[]> = {',
    ...Object.entries(result.listings)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([slug, listings]) => `  ${JSON.stringify(slug)}: ${JSON.stringify(listings)},`),
    '};',
    '',
  ].join('\n');
}

function report(date: string, feeds: readonly string[], plutoNote: string, result: ShoeImportResult, pages: number): string {
  const count = (pick: (s: ShoeImportResult['shoes'][number]) => boolean) => result.shoes.filter(pick).length;
  const both = Object.values(result.listings).filter((l) => l.length > 1).length;
  return [
    `# Hockeyschoenen-import (${date})`,
    '',
    `- **Feeds:** ${feeds.join(' en ')}${plutoNote ? ` (${plutoNote})` : ''}`,
    `- **Modellen:** ${result.shoes.length} uit ${pages} winkelpagina's (kleuren samengevoegd)`,
    `- **Veld / zaal / onbekend:** ${count((s) => s.category.value === 'veld')} / ${count((s) => s.category.value === 'zaal')} / ${count((s) => s.category.value === 'onbekend')}`,
    `- **Junior:** ${count((s) => s.ageGroup === 'junior')}`,
    `- **Bij beide winkels (zelfde EAN):** ${both}`,
    `- **Gecontroleerde modellen met feedgegevens:** ${result.curatedMatched.length}`,
    '',
    'Veld staat er alleen als Plutosport het model onder veldhockey zet; de algemene categorie "Hockeyschoenen" van PassaHockey zegt niet of het een veld- of zaalschoen is. Alle inhoudelijke eigenschappen staan op onbekend; deze modellen krijgen `noindex`.',
    '',
    `## Zelfde naam, ander artikelnummer (${result.splitByArticle.length}, apart gehouden)`,
    '',
    ...(result.splitByArticle.length
      ? result.splitByArticle.map((s) => `- ${s.name}: ${s.codes.join(', ')}`)
      : ['Geen.']),
    '',
    `## Veld én zaal volgens de winkels (${result.disciplineConflicts.length}, op onbekend gezet)`,
    '',
    ...(result.disciplineConflicts.length ? result.disciplineConflicts.map((c) => `- ${c.name}`) : ['Geen.']),
    '',
    '_Automatisch gegenereerd door `scripts/shoe-import.ts`._',
  ].join('\n');
}

async function main() {
  const args = process.argv.slice(2);
  const option = (name: string) => args.find((a) => a.startsWith(`--${name}=`))?.split('=').slice(1).join('=');
  const reportPath = args.find((a) => !a.startsWith('--')) ?? 'shoe-import.md';
  const passaOnly = args.includes('--passa-only');

  const passa = await readPassa(option('passa'));
  if ('error' in passa) throw new Error(passa.error);
  if (passa.models.length < MIN_PASSA_MODELS) {
    throw new Error(`Maar ${passa.models.length} schoenmodellen in de PassaHockey-feed; import afgebroken.`);
  }
  let pluto: Awaited<ReturnType<typeof readPlutosport>> = { models: [], note: '' };
  if (!passaOnly) {
    pluto = await readPlutosport(option('pluto'));
    if ('error' in pluto) throw new Error(`${pluto.error} Bestand niet bijgewerkt.`);
  }

  const date = new Date().toISOString().slice(0, 10);
  const feeds = passaOnly ? ['passahockey'] : ['passahockey', 'plutosport'];
  const result = buildShoeImport({ passa: passa.models, pluto: pluto.models }, CURATED_SHOES, date);
  writeFileSync(OUTPUT, generated(date, feeds, result));
  writeFileSync(
    reportPath,
    report(date, feeds, passaOnly ? 'lokaal, zonder Plutosport' : '', result, passa.models.length + pluto.models.length),
  );
  console.log(`${result.shoes.length} schoenmodellen geïmporteerd (${feeds.join(', ')}).`);
}

main().catch((error: unknown) => {
  console.error(redact(error instanceof Error ? error.message : String(error)));
  process.exitCode = 1;
});
