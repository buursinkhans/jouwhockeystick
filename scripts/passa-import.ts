// Bulk import (writes code): turns every PassaHockey stick that is in stock,
// not in our curated catalog and not older than MIN_MODEL_YEAR into a catalog
// product, and writes them to src/catalog/imported/passahockey.ts. Runs weekly
// (.github/workflows/passa-sync.yml) so prices, stock and new models stay
// current; the owner merges the resulting pull request.
// Usage: npm run passa:import -- [report.md] [feed.xml]
import { appendFileSync, readFileSync, writeFileSync } from 'node:fs';
import { getDiscipline } from '../src/catalog/discipline';
import { getCatalogProducts } from '../src/catalog/index';
import { MIN_MODEL_YEAR, toImportedProduct, type ImportSkip } from '../src/catalog/feedImport';
import { PASSAHOCKEY_FEED_URL, comparePassaFeed, parsePassaFeed } from '../src/catalog/passaFeed';
import { liveLengthsFromFeed, livePricesFromFeed } from '../src/catalog/livePrice';
import type { Product } from '../src/catalog/types';

const OUT = 'src/catalog/imported/passahockey.ts';
const PRICES_OUT = 'src/catalog/imported/passaPrices.ts';

async function main() {
  const [reportPath = 'passa-import.md', feedPath] = process.argv.slice(2);
  let xml: string;
  if (feedPath) {
    xml = readFileSync(feedPath, 'utf8');
  } else {
    const response = await fetch(PASSAHOCKEY_FEED_URL, { signal: AbortSignal.timeout(300_000) });
    if (!response.ok) throw new Error(`PassaHockey-feed niet opgehaald (HTTP ${response.status})`);
    xml = await response.text();
  }
  const models = parsePassaFeed(xml);
  // A broken or half-empty feed must never wipe the imported catalog.
  if (models.length < 200) throw new Error(`Maar ${models.length} sticks in de feed; import afgebroken.`);

  const curated = getCatalogProducts();
  const { gaps } = comparePassaFeed(
    models,
    curated.map((p) => ({
      slug: p.slug,
      brand: p.brand,
      name: p.name,
      discipline: getDiscipline(p),
      ...(p.passaSportsProductUrl && { passaSportsProductUrl: p.passaSportsProductUrl }),
    })),
  );

  const today = new Date().toISOString().slice(0, 10);
  const taken = new Set(curated.map((p) => p.slug));
  const products: Product[] = [];
  const skips: ImportSkip[] = [];
  for (const gap of gaps) {
    const result = toImportedProduct(gap, today);
    if ('skip' in result) {
      skips.push(result.skip);
    } else if (taken.has(result.product.slug)) {
      skips.push({ url: gap.url, name: gap.name, reason: `slug "${result.product.slug}" bestaat al` });
    } else {
      taken.add(result.product.slug);
      products.push(result.product);
    }
  }
  products.sort((a, b) => a.slug.localeCompare(b.slug));

  writeFileSync(
    OUT,
    [
      '// GENERATED by `npm run passa:import` from the PassaHockey product feed (TradeTracker).',
      '// Do not edit by hand: the weekly sync overwrites this file. To curate a stick, copy it',
      '// to src/catalog/products/, remove `feedImport` and register it in src/catalog/index.ts.',
      "import type { Product } from '../types';",
      '',
      `export const PASSAHOCKEY_IMPORT_DATE = '${today}';`,
      '',
      'export const PASSAHOCKEY_PRODUCTS: Product[] = [',
      ...products.map((p) => `  ${JSON.stringify(p)},`),
      '];',
      '',
    ].join('\n'),
  );

  // Current prices of our own (curated) PassaHockey sticks: the site uses these
  // instead of the brand's list price (src/catalog/livePrice.ts).
  const livePrices = livePricesFromFeed(curated, models);
  // Lengths in stock, for the size choice in "Waar te koop" (decision log 2026-10-27).
  const liveLengths = liveLengthsFromFeed(curated, models);
  writeFileSync(
    PRICES_OUT,
    [
      '// GENERATED by `npm run passa:import` from the PassaHockey product feed (TradeTracker).',
      '// Current price per curated stick that links to PassaHockey; see src/catalog/livePrice.ts.',
      "import type { LivePrices } from '../livePrice';",
      '',
      `export const PASSAHOCKEY_LIVE_PRICES: LivePrices = ${JSON.stringify({ date: today, prices: livePrices, lengths: liveLengths })};`,
      '',
    ].join('\n'),
  );

  const count = <T extends string>(values: T[]) =>
    Object.entries(values.reduce<Record<string, number>>((acc, v) => ({ ...acc, [v]: (acc[v] ?? 0) + 1 }), {}))
      .sort(([, a], [, b]) => b - a)
      .map(([k, n]) => `${k}: ${n}`)
      .join(', ');
  const reasons = count(skips.map((s) => s.reason.replace(/"[^"]*"/, '"…"')));
  const report = [
    `# PassaHockey-import (${today})`,
    '',
    `${products.length} sticks uit de feed van PassaHockey staan in de catalogus (naast ${curated.length} sticks die we met de hand bijhouden). Alleen sticks die leverbaar zijn, niet al in de catalogus staan en niet ouder zijn dan modeljaar ${MIN_MODEL_YEAR} (waar het jaar bekend is).`,
    '',
    `- Veld/zaal: ${count(products.map((p) => p.discipline?.value ?? 'veld'))}`,
    `- Kromming bekend: ${products.filter((p) => p.bowProfile).length} · carbonpercentage bekend: ${products.filter((p) => p.carbonPercentage).length} · met foto: ${products.filter((p) => p.imageUrl).length}`,
    `- Niveau (eigen inschatting): ${count(products.map((p) => p.experienceLevel.value))}`,
    `- Merken: ${count(products.map((p) => p.brand))}`,
    `- Actuele PassaHockey-prijs voor ${Object.keys(livePrices).length} van onze eigen sticks`,
    '',
    `## Niet opgenomen (${skips.length})`,
    '',
    reasons ? `Redenen: ${reasons}.` : 'Geen.',
    '',
    ...skips.slice(0, 60).map((s) => `- ${s.name} — ${s.reason} — ${s.url}`),
    ...(skips.length > 60 ? [`- … en ${skips.length - 60} meer`] : []),
    '',
    '_Pagina’s van geïmporteerde sticks staan op noindex en niet in de sitemap; ze tellen pas mee voor Google als een stick met de hand is verrijkt._',
  ].join('\n');
  writeFileSync(reportPath, report);
  if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `imported=${products.length}\n`);
  console.log(`${products.length} sticks geïmporteerd, ${skips.length} niet opgenomen → ${OUT}`);
}

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
